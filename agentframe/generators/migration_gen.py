_VERSIONS_GITKEEP = ""


class MigrationGenerator(BaseGenerator):
    """Generates the Alembic project structure (idempotent).

    Migration scripts themselves are created by `agentframe migrate`
    or the deploy pipeline — NOT by this generator.
    """

    def generate(self, graph: Graph) -> dict[str, str]:
        return {
            "../alembic.ini": _ALEMBIC_INI,
            "../alembic/env.py": _ENV_PY,
            "../alembic/script.py.mako": _SCRIPT_MAKO,
            "../alembic/versions/.gitkeep": _VERSIONS_GITKEEP,
        }
